#!/usr/bin/env python3
"""Generate the CalcOS 8x12 console font from a monospace TTF.

The PicoCalc panel is 320x320. An 8x12 cell gives a 40x26 console: the same
40 columns as an 8x8 cell but half again as much height per glyph, which is
what makes small text legible. This is the geometry MMBasic uses on this
hardware, for the same reason.

The glyphs are rendered here from DejaVu Sans Mono rather than copied from
another project: MMBasic's own font is adapted from the Rinky-Dink UTFT set,
which is CC BY-NC-SA and so cannot go into an MIT-licensed program.

Size 11 at a two-pixel top offset is the largest rendering whose every glyph
fits a 12-row cell whole: at size 12 the tails of g, y, p, q, j and the ends
of the taller brackets are cut off by the bottom of the cell, which is what
makes a dense screen look smeared. Verified by tests/test_font.py.

Usage: python3 tools/make_font.py > platform/font.c
"""
from PIL import Image, ImageDraw, ImageFont
import sys

FACES = [("calcos_font",      "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"),
         ("calcos_font_bold", "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf")]
SIZE = 11         # glyph size inside the 8x12 cell
DY = -2           # vertical offset: chosen so nothing is clipped
DX = 0
THRESH = 110
W, H = 8, 12


def bits(ch, path):
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    d.text((DX, DY), ch, font=ImageFont.truetype(path, SIZE), fill=255)
    rows = []
    for y in range(H):
        b = 0
        for x in range(W):
            if img.getpixel((x, y)) >= THRESH:
                b |= 1 << x        # bit 0 is the leftmost pixel
        rows.append(b)
    return rows


def main():
    print("/* Generated by tools/make_font.py. 8x12 cell, bit 0 = left pixel. */")
    print("/* Rendered at size %d, offset %d, so lines keep their leading. */"
          % (SIZE, DY))
    for name, path in FACES:
        print("")
        print("const unsigned char %s[95][%d] = {" % (name, H))
        for c in range(32, 127):
            r = bits(chr(c), path)
            ch = chr(c).replace("\\", "\\\\").replace("'", "\\'")
            print("    {%s},  /* %3d '%s' */"
                  % (",".join("0x%02x" % v for v in r), c, ch))
        print("};")


if __name__ == "__main__":
    main()
